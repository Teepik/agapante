export const lyceeById = Object.fromEntries(lycees.map((l) => [l.id, l])) as Record<string, Lycee>;

/** Internat ouvert aux lycéens (et pas seulement aux élèves de prépa). */
export function lyceeInternat(l: Lycee): "lycee" | "prepas" | null {
  if (!l.internat?.existe) return null;
  return /CPGE|prépa|post-bac|étudiants/i.test(`${l.internat.pour ?? ""} ${l.internat.des ?? ""}`) ? "prepas" : "lycee";
}

/** Étiquette courte de l'internat, pour les listes. */
export function internatTag(l: Lycee): string | null {
  const k = lyceeInternat(l);
  if (!k) return null;
  if (k === "prepas") return "Internat des prépas";
  const pour = l.internat?.pour ?? "";
  if (/garçons/.test(pour) && /filles/.test(pour)) return "Internat";
  if (/garçons/.test(pour)) return "Internat garçons";
  if (/filles/.test(pour)) return "Internat filles";
  return "Internat";
}
